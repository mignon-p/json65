        sta evtype
        jsr call_callback
        bcs error
        lda #par_need_colon
        putstate st::parser_st
        clc
        rts                     ; success exit
.endproc                ; handle_string

;; unescape \\ and \u in the string buffer.
;; returns carry set on error.  clear on success.
;; clobbers all registers.
;;
;; Uses a two-pointer compaction loop through strbuf:
;;   y   = read index (0 .. str_idx-1, scanning raw bytes as stored by the lexer)
;;   tmp1 = write index (output bytes are compacted toward the front)
;; tmp2 holds str_idx (the original string length).
;; When a \\ is found, it is replaced by a single backslash.
;; When a \u is found, the following 4 hex digits are decoded and the Unicode
;; codepoint is converted to UTF-8 in-place via long1toutf8.
;; Surrogate pairs (\uD800-\uDBFF immediately followed by \uDC00-\uDFFF) are
;; recognised and combined into a single codepoint before UTF-8 encoding.
.proc unescape_unicode
        getstate st::str_idx
        sta tmp2
        ldy #0
        sty tmp1
loop:   cpy tmp2
        beq done
        lda (strbuf),y
        iny
        cmp #$5c                ; backslash
        beq escape
loop1:  sty tmp5
        ldy tmp1
        sta (strbuf),y
        inc tmp1
        ldy tmp5
        jmp loop
escape: cpy tmp2
        beq error
        lda (strbuf),y
        iny
        cmp #$5c                ; backslash
        beq loop1               ; \\ → emit single backslash
        cmp #'u'
        beq unicode
error:  sec
        rts
unicode:
        jsr read4hexintosreg    ; decode 4 hex digits into sreg
        bcs error
        jsr movesregtolong1     ; zero-extend sreg into long1
        ;; Look ahead: if the next two bytes in the buffer are '\u' and the
        ;; value we just read is a left surrogate (D800-DBFF), try to consume
        ;; a right surrogate (DC00-DFFF) to form a combined codepoint.
        lda (strbuf),y
        cpy tmp2
        beq bmp
        cmp #$5c                ; backslash
        bne bmp
        iny
        cpy tmp2
        beq bmp0
        lda (strbuf),y
        cmp #'u'
        beq check_surrogate
bmp0:   dey
bmp:    jsr long1toutf8         ; encode codepoint in long1 as UTF-8 into strbuf
        jmp loop
bmp1:   pla
        tay
        jmp bmp
check_surrogate:
        jsr is_sreg_left_surrogate
        bcc bmp0                ; not a left surrogate; treat as BMP char
        tya
        sub #1                  ; save read position just before the second \u
        pha
        iny                     ; skip past the 'u'
        jsr read4hexintosreg    ; decode the second \uXXXX into sreg
        bcs bmp1                ; malformed hex: abandon surrogate, restore pos
        jsr is_sreg_right_surrogate
        bcc bmp1                ; not a right surrogate: abandon, restore pos
        pla                     ; discard saved position (surrogate pair consumed)
        jsr combine_surrogates  ; merge left (long1) + right (sreg) → long1
        jmp bmp
done:   lda tmp1
        putstate st::str_idx
        clc
        rts
.endproc                ; unescape_unicode

;; reads 4 hex digs from strbuf at y into sreg.
;; (buffer length is in tmp2)
;; on success, carry clear, leaves y pointing after 4 digs.
;; on failure, carry set.
.proc read4hexintosreg
        ldx #4
loop:   jsr shift_sreg_left_4bits
        jsr or1hexintosreg
        bcs done
        dex
        bne loop
        clc
done:   rts
.endproc                ; read4hexintosreg

;; clobbers a, preserves x and y.
.proc shift_sreg_left_4bits
        lda sreg
        asl a
        rol sreg+1
        asl a
        rol sreg+1
        asl a
        rol sreg+1
        asl a
        rol sreg+1
        sta sreg
        rts
.endproc                ; shift_sreg_left_4bits

;; reads 1 hex dig from strbuf at y into low 4 bits of sreg.
;; (buffer length is in tmp2)
;; on success, carry clear, leaves y pointing after digit.
;; on failure, carry set.
.proc or1hexintosreg
        cpy tmp2
        beq fail
        lda (strbuf),y
        iny
        jsr hex_dig_to_nibble
        bcs fail
        ora sreg
        sta sreg
        clc
        rts
fail:   sec
        rts
.endproc                ; or1hexintosreg

;; converts ascii char in a to nibble in a.
;; sets carry if not a hex digit.
;; preserves x and y.
.proc hex_dig_to_nibble
        cmp #'0'
        blt fail
        cmp #'9'+1
        bge tryupper
        sub #'0'
        clc
        rts
tryupper:
        cmp #'A'
        blt fail
        cmp #'F'+1
        bge trylower
        sub #'A'-10
        clc
        rts
trylower:
        cmp #'a'
        blt fail
        cmp #'f'+1
        bge fail
        sub #'a'-10
        clc
        rts
fail:   sec
        rts
.endproc                ; hex_dig_to_nibble

;; zero-extends sreg into long1.
;; clobbers a, preserves x and y
.proc movesregtolong1
        lda sreg
        sta long1
        lda sreg+1
        sta long1+1
        lda #0
        sta long1+2
        sta long1+3
        rts
.endproc                ; movesregtolong1

;; converts long1 to utf8 in strbuf at tmp1.
;; (output index is in tmp1)
;; preserves y.
;;
;; UTF-8 encoding ranges (RFC 3629):
;;   U+0000..U+007F   → 0xxxxxxx                    (1 byte)
;;   U+0080..U+07FF   → 110xxxxx 10xxxxxx            (2 bytes)
;;   U+0800..U+FFFF   → 1110xxxx 10xxxxxx 10xxxxxx   (3 bytes)
;;   U+10000..U+10FFFF→ 11110xxx 10xxxxxx 10xxxxxx 10xxxxxx (4 bytes)
;;
;; The strategy is to use utf8_shift to reorganise the data bits of the
;; codepoint across the long1 bytes, then apply the appropriate header bits
;; (10xxxxxx continuation prefix, or 110/1110/11110 leading prefix), and
;; finally write the bytes in reverse order via writeutf8.  x is set to
;; (byte_count - 1) on the jmp done path so writeutf8 writes the right count.
.proc long1toutf8
        sty tmp5
        ldy tmp1
        lda long1+2
        bne len4
        lda long1+1
        beq latin1
        cmp #8              ; long1+1 >= 8 means codepoint >= $0800
        bge len3
len2:   ldx #1
        jsr utf8_shift      ; move bits 7:6 of long1 into bits 1:0 of long1+1
        lda long1
        and #%00111111
        ora #%10000000      ; 10xxxxxx continuation byte
        sta long1
        lda long1+1
        and #%00011111
        ora #%11000000      ; 110xxxxx leading byte (5 data bits)
        sta long1+1
        ldx #1
        jmp done
len3:   ldx #1
        jsr utf8_shift      ; move bits 7:6 of long1   into bits 1:0 of long1+1
        ldx #2
        jsr utf8_shift      ; move bits 7:6 of long1+1 into bits 1:0 of long1+2
        lda long1
        and #%00111111
        ora #%10000000      ; 10xxxxxx
        sta long1
        lda long1+1
        and #%00111111
        ora #%10000000      ; 10xxxxxx
        sta long1+1
        lda long1+2
        and #%00001111
        ora #%11100000      ; 1110xxxx leading byte (4 data bits)
        sta long1+2
        ldx #2
        jmp done
len4:   ldx #1
        jsr utf8_shift
        ldx #2
        jsr utf8_shift
        ldx #3
        jsr utf8_shift
        lda long1
        and #%00111111
        ora #%10000000      ; 10xxxxxx
        sta long1
        lda long1+1
        and #%00111111
        ora #%10000000      ; 10xxxxxx
        sta long1+1
        lda long1+2
        and #%00111111
        ora #%10000000      ; 10xxxxxx
        sta long1+2
        lda long1+3
        and #%00000111
        ora #%11110000      ; 11110xxx leading byte (3 data bits)
        sta long1+3
        ldx #3
        jmp done
latin1: lda long1
        bmi len2            ; U+0080..U+00FF need 2-byte encoding despite fitting in a byte
        ldx #0              ; U+0000..U+007F: 1 byte, already correct bit pattern
done:   jsr writeutf8
        sty tmp1
        ldy tmp5
        rts
.endproc                ; long1toutf8

;; writes the first x+1 bytes of long1, in reverse order,
;; to strbuf, starting at y.  advances y.
;; clobbers a, x.
.proc writeutf8
        lda long1,x
        sta (strbuf),y
        iny
        dex
        bpl writeutf8
        rts
.endproc                ; writeutf8

;; shift the last 4-x bytes of long1 left by 2 bits.
;; clobbers a, x.  preserves y.
.proc shift_left_by_2
        stx tmp6
        jsr shift_left_by_1
        ldx tmp6
shift_left_by_1:
        asl long1,x
loop:   php
        cpx #3
        beq done
        inx
        plp
        rol long1,x
        jmp loop
done:   plp
        rts
.endproc                ; shift_left_by_2

;; utf8_shift(x): "bubble" the top 2 bits of long1[x-1] into the bottom 2
;; bits of long1[x], making room for a UTF-8 continuation marker in long1[x-1].
;;
;; Mechanically: shift the entire 32-bit long1 left by 2 (carrying bits from
;; byte x-1 into byte x), then shift byte x-1 (= x after dex) right by 2 to
;; undo the shift on that byte only.  The net result:
;;   long1[x]   gains bits 7:6 of the original long1[x-1] in its bits 1:0
;;   long1[x-1] retains its original bits 5:0 in positions 5:0 (bits 7:6 = 0)
;;
;; clobbers a, x.  preserves y.
.proc utf8_shift
        dex
        txa
        pha
        jsr shift_left_by_2     ; shift all of long1 left 2 bits
        pla
        tax
        lsr long1,x             ; undo the 2-bit shift on byte[x] = original[x-1]
        lsr long1,x
        rts
.endproc                ; utf8_shift

;; preserves y.
;; sets carry if sreg is a left surrogate.
.proc is_sreg_left_surrogate
        lda sreg+1
        and #$fc
        cmp #$d8
        beq yes
        clc
        rts
yes:    sec
        rts
.endproc                ; is_sreg_left_surrogate

;; preserves y.
;; sets carry if sreg is a right surrogate.
.proc is_sreg_right_surrogate
        lda sreg+1
        and #$fc
        cmp #$dc
        beq yes
        clc
        rts
yes:    sec
        rts
.endproc                ; is_sreg_right_surrogate

;; combine left surrogate in long1 with right surrogate in sreg.
;; result in long1.  preserves y.
;;
;; Formula (RFC 2781): U = 0x10000 + (L_bits << 10) + R_bits
;;   where L_bits = left_surrogate  & 0x3FF  (bits 9:0)
;;         R_bits = right_surrogate & 0x3FF  (bits 9:0)
;;
;; On entry, movesregtolong1 has already placed the left surrogate in long1
;; and read4hexintosreg has placed the right surrogate in sreg.
;;
;; Implementation: extract L_bits[9:8] from long1+1 (bits 1:0), then shift
;; the 10-bit L_bits value left by 10 (= into bits 19:10) by moving long1[0]
;; to long1[1] and shifting that pair left 2 bits.  Then OR in R_bits (10 bits
;; from sreg), and finally add 0x10000 by incrementing long1+2.
.proc combine_surrogates
        lda long1+1
        and #3              ; keep L_bits[9:8] (2 bits) in A
        sta long1+2         ; long1+2 = L_bits[9:8]
        lda long1
        sta long1+1         ; long1+1 = L_bits[7:0]
        asl long1+1
        rol long1+2         ; shift left 1: long1+2:long1+1 = L_bits << 9 so far
        asl long1+1
        rol long1+2         ; shift left 2: long1+2:long1+1 = L_bits << 10
        lda sreg
        sta long1           ; long1+0 = R_bits[7:0]
        lda sreg+1
        and #3              ; R_bits[9:8]
        ora long1+1         ; merge with L_bits[1:0] (which are now at bits 1:0)
        sta long1+1
        inc long1+2         ; add 0x10000 (bit 16)
        rts
.endproc                ; combine_surrogates

;; parse signed integer in strbuf (length in str_idx).
;; on success, carry clear and result in long1 (regsave).
;; on integer overflow, carry set and overflow set.
;; on illegal character, carry set and overflow clear.
;; clobbers a, x, and y.
.proc parse_signed_integer
        ldy #0
        lda (strbuf),y
        cmp #'-'
        beq negative
        jsr parse_unsigned_integer
        bcs done                ; overflow of 32-bit int, C and V are set
        bit long1+3
        bpl done                ; if hi bit is clear, it is okay
not_okay:
        ;; Set both carry and overflow to signal "integer overflow" to the
        ;; caller (so it can fall back to J65_NUMBER).
        ;; Trick: 'bit an_rts' reads the byte at 'an_rts', which is the RTS
        ;; opcode ($60 = %0110_0000).  The BIT instruction sets V from bit 6
        ;; of the operand, so V is set.  SEC sets C.
        sec                     ; set carry
        bit an_rts              ; set overflow (V) because RTS opcode $60 has bit 6 set
done:
an_rts: rts
negative:
        iny
        jsr parse_unsigned_integer
        bcs done                ; overflow of 32-bit int, C and V are set
        lda #$7f
        bit long1+3
        bpl okay                ; if hi bit is clear, it is okay
        bne not_okay            ; if hi byte is not $80, it is not okay
        lda long1+2
        ora long1+1
        ora long1
        bne not_okay            ; only okay if 3 least significant bytes are 0
okay:   jsr resteax
        jsr negeax
        jsr saveeax
        clc
        jmp done
.endproc                ; parse_signed_integer

;; parse unsigned integer in strbuf, starting at y.
;; on success, carry clear and result in long1 (regsave).
;; on integer overflow, carry set and overflow set.
;; on illegal character, carry set and overflow clear.
;; clobbers a and y.  preserves x.
.proc parse_unsigned_integer
        lda #0
        sta long1
        sta long1+1
        sta long1+2
        sta long1+3
loop:   tya
        ldy #st::str_idx
        cmp (state),y
        bge done
        tay
        jsr multiply_long1_by_10
        bcs overflow
        lda (strbuf),y
        jsr hex_dig_to_nibble
        bcs error
        jsr add_a_to_long1
        iny
        bcc loop
overflow:
        bit an_rts              ; bit on an rts instruction will set overflow
an_rts: rts                     ; carry and overflow are both set
done:   clc
        rts                     ; success: carry clear
error:  clv
        sec
        rts                     ; carry set, overflow clear
.endproc                ; parse_unsigned_integer

;; multiplies long1 by 10. clobbers a and long2. preserves x y.
;; returns with carry set if result overflows a 32-bit unsigned long.
;;
;; Algorithm: 10x = 2x + 8x
;;   1. Shift long1 left by 1  → long1 = 2x  (save a copy in long2)
;;   2. Shift long1 left by 1  → long1 = 4x
;;   3. Shift long1 left by 1  → long1 = 8x
;;   4. Add long2 (= 2x)       → long1 = 10x
;; Any shift that sets carry means the result would overflow 32 bits.
.proc multiply_long1_by_10
        jsr shift_long1_left_by_1   ; long1 = 2x
        bcs done
        lda long1                   ; save 2x in long2
        sta long2
        lda long1+1
        sta long2+1
        lda long1+2
        sta long2+2
        lda long1+3
        sta long2+3
        jsr shift_long1_left_by_1   ; long1 = 4x
        bcs done
        jsr shift_long1_left_by_1   ; long1 = 8x
        bcs done
        lda long1                   ; long1 = 8x + 2x = 10x
        add long2
        sta long1
        lda long1+1
        adc long2+1
        sta long1+1
        lda long1+2
        adc long2+2
        sta long1+2
        lda long1+3
        adc long2+3
        sta long1+3
done:   rts
.endproc                ; multiply_long1_by_10

;; shifts long1 left by 1.  clobbers a; preserves x and y.
.proc shift_long1_left_by_1
        asl long1
        rol long1+1
        rol long1+2
        rol long1+3
        rts
.endproc                ; shift_long1_left_by_1

;; add a to long1.  sets carry if result overflows an unsigned long.
;; clobbers a; preserves x and y.
.proc add_a_to_long1
        add long1
        sta long1
        lda long1+1
        adc #0
        sta long1+1
        lda long1+2
        adc #0
        sta long1+2
        lda long1+3
        adc #0
        sta long1+3
        rts
.endproc                ; add_a_to_long1

;; parse "null", "false", or "true" in strbuf (length in str_idx).
;; on success, carry clear and a contains event number.
;; on failure, carry set.  clobbers x and y.
.proc identify_literal
        getstate st::str_idx
        cmp #4
        beq len4
        cmp #5
        beq len5
fail:   sec
        rts
len4:   lda #<str_null
        ldx #>str_null
        ldy #3
        jsr compare_strings
        beq got_null
        lda #<str_true
        ldx #>str_true
        ldy #3
        jsr compare_strings
        bne fail
        lda #J65_TRUE
        clc
        rts
got_null:
        lda #J65_NULL
        clc
        rts
len5:   lda #<str_false
        ldx #>str_false
        ldy #4
        jsr compare_strings
        bne fail
        lda #J65_FALSE
        clc
        rts

        .rodata
str_null:
        .byte "null"
str_true:
        .byte "true"
str_false:
        .byte "false"
        .code

.endproc                ; identify_literal

;; compares string (of length y+1) at strbuf with string pointed to
;; by a (lo byte) and x (hi byte).
;; returns with zero flag set if strings match, or zero flag clear
;; if they do not.
;; clobbers ptr1.
.proc compare_strings
        sta ptr1
        stx ptr1+1
loop:   lda (strbuf),y
        cmp (ptr1),y
        bne done
        dey
        bpl loop
        lda #0                  ; set zero flag
done:   rts
.endproc                ; compare_strings

;; Handle a literal (a number, or null, true, or false).
;; On entry, a should contain flags.  (prop_lit, prop_int, prop_num)
;; Clobbers all registers.
;; On success, returns carry clear.
;; On error, returns carry set with error event in a.
.proc handle_literal
        tax
        getstate st::parser_st
        cmp #par_ready
        beq p_ready
        cmp #par_ready_or_close_array
        beq p_ready
parse_err:
        lda #J65_PARSE_ERROR
        sec
error:  rts                     ; error exit
p_ready:
        txa
        bit flags_prop_lit
        bne keyword
        bit flags_prop_int
        bne integer
number: lda #J65_NUMBER
do_callback:
        sta evtype
        jsr call_callback
        bcs error
        getstate st::parser_st2 ; get next parser state in a
        putstate st::parser_st
        clc
        rts                     ; success exit
integer:
        jsr parse_signed_integer
        bcs not_integer
        ldy #st::long_val       ; copy long1 to long_val
        lda long1
        sta (state),y
        iny
        lda long1+1
        sta (state),y
        iny
        lda long1+2
        sta (state),y
        iny
        lda long1+3
        sta (state),y
        lda #J65_INTEGER
        jmp do_callback
not_integer:
        bvs number
        jmp parse_err
keyword:
        jsr identify_literal
        bcs parse_err
        jmp do_callback

        .rodata
flags_prop_lit:
        .byte prop_lit
flags_prop_int:
        .byte prop_int
        .code

.endproc                ; handle_literal

;; push a onto the state stack.
;; carry clear on success.
;; carry set on error, with error event in a.
;; clobbers x, y.
;;
;; The stack grows downward within the first 256-byte page.  stack_idx starts
;; at 255 (empty) and decrements on each push.  The value is written at the
;; offset given by the current stack_idx, then stack_idx is decremented.
;; The stack is full if stack_idx would go below stack_min.
.proc push_state_stack
        tax
        getstate st::stack_idx
        ldy #st::stack_min
        cmp (state),y
        blt stack_full
        tay
        txa
        sta (state),y           ; store value at current stack_idx
        dey                     ; decrement stack_idx
        tya
        putstate st::stack_idx
        clc
        rts
stack_full:
        lda #J65_NESTING_TOO_DEEP
        sec
        rts
.endproc                ; push_state_stack

;; pop the state stack.
;; carry clear on success, with popped state in a.
;; carry set on error, with error event in a.
;; clobbers x, y.
;;
;; Increment stack_idx first, then read the value.  If the incremented
;; stack_idx wraps around to 0 (was 255 = empty), the stack is empty.
.proc pop_state_stack
        getstate st::stack_idx
        tay
        iny                     ; increment stack_idx (will wrap to 0 if was 255)
        beq stack_empty
        lda (state),y
        tax
        tya
        putstate st::stack_idx
        txa
        clc
        rts
stack_empty:
        lda #J65_PARSE_ERROR
        sec
        rts
.endproc                ; pop_state_stack

;; increment the long at state+y to state+y+3 by 1.
;; clobbers a and y.
.proc inc_state_long
        lda (state),y
        add #1
        sta (state),y
        bcc done                ; short circuit for speed
        iny
        lda (state),y
        adc #0
        sta (state),y
        iny
        lda (state),y
        adc #0
        sta (state),y
        iny
        lda (state),y
        adc #0
        sta (state),y
done:   rts
.endproc                ; inc_state_long

