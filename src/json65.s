;; Memory layout of the 512-byte j65_parser struct
;; -------------------------------------------------------
;; The 512 bytes are split into two consecutive 256-byte pages:
;;
;;   Page 0 (bytes   0-255): the 'st' struct at the bottom (sizeof(st) bytes),
;;                            followed by the parser state stack growing
;;                            downward from offset 255 toward offset sizeof(st).
;;                            'state' (in ZP) points here.
;;
;;   Page 1 (bytes 256-511): the string/number accumulation buffer.
;;                            'strbuf' (in ZP) points here; it is always
;;                            state+256, i.e. state with the high byte
;;                            incremented by 1.  This means _j65_get_string()
;;                            can return the buffer address with a single INX.

;; zero page locations
        state     = regbank
        strbuf    = regbank + 2
        inbuf     = regbank + 4
        inbuflast = tmp4         ; length - 1
        charidx   = tmp3         ; position in inbuf
        evtype    = tmp2         ; only used as an argument to call_callback
        esc_code  = tmp2         ; only used as an argument to lookup_escape
        tmp5      = sreg
        tmp6      = sreg+1
        long1     = regsave
        long2     = ptr1
;; zero page locations (for _j65_parse)
        jlen      = ptr3

;; character properties
        prop_ws   = %10000000   ; must be hi bit (we use bmi/bpl to test)
        prop_str  = %01000000
        prop_lit  = %00100000
        prop_int  = %00010000
        prop_num  = %00001000
        prop_sc   = %00000111   ; mask for structural character field

;; j65_event
.enum
        J65_NULL        = 0
        J65_FALSE       = 1
        J65_TRUE        = 2
        J65_INTEGER     = 3        ; integer and string
        J65_NUMBER      = 4        ; string
        J65_STRING      = 5        ; string
        J65_KEY         = 6        ; string
        J65_START_OBJ   = 7
        J65_END_OBJ     = 8
        J65_START_ARRAY = 9
        J65_END_ARRAY   = 10
.endenum

;; j65_status
.enum
        J65_DONE      = 1
        J65_WANT_MORE = 2

        ; errors
        J65_PARSE_ERROR        = $80
        J65_ILLEGAL_CHAR
        J65_ILLEGAL_ESCAPE
        J65_NESTING_TOO_DEEP
        J65_STRING_TOO_LONG
        J65_EXPECTED_STRING
        J65_EXPECTED_COLON
        J65_EXPECTED_COMMA
        J65_EXPECTED_OBJ_END
        J65_EXPECTED_ARRAY_END
        J65_USER_ERROR             ; must be last.  not generated by parser.
.endenum

;; lexer state
.enum
        lex_ready
        lex_literal
        lex_string
        lex_str_escape
.endenum

;; parser state (should fit in 3 bits; otherwise need to change l_ready)
;; (order needs to match dispatch_tab and literal_errors)
.enum
        par_ready
        par_ready_or_close_array
        par_key
        par_key_or_close_object
        par_need_colon
        par_need_comma_or_close_array
        par_need_comma_or_close_object
        par_done
.endenum

;; structural characters (should fit in 3 bits)
.enum
        sc_none                 ; an illegal character
        sc_lsq                  ; [
        sc_lcur                 ; {
        sc_rsq                  ; ]
        sc_rcur                 ; }
        sc_colon                ; :
        sc_comma                ; ,
        sc_quote                ; "
.endenum

;; state variables
;; The parser state stack lives in the same 256-byte page immediately above
;; these fixed fields.  stack_idx is the current top-of-stack offset (starts
;; at 255 = empty; decrements on push, increments on pop).  stack_min is the
;; lowest offset the stack may reach (= 256 - max_depth, clamped to at least
;; sizeof(st) so the stack never collides with the fixed fields below it).
.struct st
        callback   .word        ; these two must be first and in this order
        context    .word
        file_off   .dword       ; total bytes consumed so far
        line_off   .dword       ; file_off at start of current line
        line_num   .dword       ; 0-based current line number
        col_num    .dword       ; bytes consumed on current line (before current char)
        long_val   .dword       ; parsed integer value (for J65_INTEGER events)
        lexer_st   .byte        ; current lexer state (lex_ready/literal/string/escape)
        parser_st  .byte        ; current parser state (what token is expected next)
        parser_st2 .byte        ; saved outer parser state (restored after a value)
        str_idx    .byte        ; write cursor into string buffer (also = string length)
        stack_idx  .byte        ; top-of-stack byte offset within page 0 (255 = empty)
        flags      .byte        ; during literal scan: remaining candidate prop bits;
                                ; during string scan: 1 if deferred \\ or \u present
        stack_min  .byte        ; minimum allowed stack_idx (= 256 - max_depth)
        prev_char  .byte        ; last consumed byte (used to detect CRLF pairs)
.endstruct

;; loads a with specified state variable.  clobbers y.
.macro getstate arg
        ldy #arg
        lda (state),y
.endmacro               ; getstate

;; stores a to specified state variable.  clobbers y.
.macro putstate arg
        ldy #arg
        sta (state),y
.endmacro               ; putstate

;; pushes regbank (caller-saved registers) onto 6502 stack
.macro save_regbank
        .repeat 6, i
        lda regbank+i
        pha
        .endrep
.endmacro               ; save_regbank

;; pops regbank (caller-saved registers) off of 6502 stack
.macro restore_regbank
        .repeat 6, i
        pla
        sta regbank+5-i
        .endrep
.endmacro               ; restore_regbank

;; sign-extends a into ax.  clobbers y.
.macro signextend
        tay
        asl
        lda #0
        sbc #0
        eor #$ff
        tax
        tya
.endmacro               ; signextend

        .code

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;;                             j65_init                             ;;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

;; void __fastcall__ j65_init(j65_state *s, void *ctx, j65_callback cb, uint8_t max_depth);
;;
;; C stack frame at entry (sp points to bottom, growing upward):
;;   sp+0 .. sp+1 : callback (cb)     -- stored directly into st::callback
;;   sp+2 .. sp+3 : context  (ctx)    -- stored directly into st::context
;;   sp+4 .. sp+5 : state pointer (s) -- the j65_parser to initialise
;;   A             : max_depth         -- last arg in fastcall arrives in A
;;
;; regbank is caller-saved, so we temporarily borrow ptr1 to hold the old
;; regbank value while we clobber 'state' (regbank) to point at 's'.
.proc _j65_init
        sta tmp1                ; save max_depth
        lda state               ; save first 2 bytes of regbank
        sta ptr1
        lda state+1
        sta ptr1+1

        ldy #4                  ; get state pointer off stack
        lda (sp),y
        sta state
        iny
        lda (sp),y
        sta state+1

        ldy #.sizeof(st) - 1    ; clear state variables to 0
        lda #0
loop:   sta (state),y
        dey
        bpl loop

        lda #par_done
        putstate st::parser_st2
        lda #$ff
        putstate st::stack_idx
        ;; stack_min = max(sizeof(st), 256 - max_depth)
        ;; Storing 256-max_depth as an 8-bit value is equivalent to 0-max_depth
        ;; because 256 mod 256 = 0.  The clamp ensures the stack never grows
        ;; into the fixed fields of the st struct.
        lda #0
        sub tmp1                ; subtract max depth from 256
        cmp #.sizeof(st)
        bge depth_ok
        lda #.sizeof(st)
depth_ok:
        putstate st::stack_min

        ldy #3                  ; copy callback and context from stack to state
loop1:  lda (sp),y
        sta (state),y
        dey
        bpl loop1

        lda ptr1                ; restore first 2 bytes of regbank
        sta state
        lda ptr1+1
        sta state+1
        jmp incsp6              ; tail call to remove args from stack
.endproc                ; _j65_init

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;;                             j65_parse                            ;;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

;; int8_t __fastcall__ j65_parse(j65_state *s, const char *buf, size_t len)
;;
;; The inner 'parse' routine uses an 8-bit index into inbuf, so it can only
;; handle up to 256 bytes at a time.  This outer wrapper slices 'buf' into
;; 256-byte chunks and calls parse() on each one.  inbuflast holds the index
;; of the last valid byte (= length-1 for the final partial chunk, $FF for
;; full 256-byte chunks).  After each full chunk, inbuf's high byte is
;; incremented to advance to the next 256-byte page, and file_off is updated.
.proc _j65_parse
        sta jlen
        stx jlen+1
        save_regbank            ; save regbank onto 6502 stack
        ldy #0                  ; move state and buf from C stack to regbank
        lda (sp),y
        sta inbuf
        iny
        lda (sp),y
        sta inbuf+1
        iny
        lda (sp),y
        sta state
        sta strbuf
        iny
        lda (sp),y
        sta state+1
        add #1                  ; strbuf is state+256
        sta strbuf+1
        jsr incsp4              ; remove state and buf from C stack
loop:   lda jlen+1
        beq leftovers
        pha                     ; save jlen on 6502 stack
        lda jlen
        pha
        lda #$ff
        sta inbuflast
        jsr parse
        tax
        lda #$ff                ; increment file_off by 256
        jsr add_a_plus_1_to_file_off
        pla                     ; restore jlen off 6502 stack
        sta jlen
        pla
        sub #1                  ; decrement jlen by 256
        sta jlen+1
        cpx #J65_WANT_MORE
        bne done                ; error or success; don't need to parse more
        inc inbuf+1             ; add 256 to inbuf
        jmp loop
leftovers:                      ; hi byte of jlen is zero
        ldx jlen
        beq done                ; if length was a multiple of 256
        dex
        stx inbuflast
        txa
        pha
        jsr parse
        tax
        pla
        jsr add_a_plus_1_to_file_off
done:   restore_regbank         ; restore regbank off of 6502 stack
        txa                     ; return value
        signextend
        rts
.endproc                ; _j65_parse

;; adds a plus 1 to file_off.
;; clobbers a and y.  preserves x.
.proc add_a_plus_1_to_file_off
        ldy #st::file_off
        sec
        adc (state),y           ; file_off
        sta (state),y
        iny
        lda (state),y           ; file_off+1
        adc #0
        sta (state),y
        iny
        lda (state),y           ; file_off+2
        adc #0
        sta (state),y
        iny
        lda (state),y           ; file_off+3
        adc #0
        sta (state),y
        rts
.endproc                ; add_a_plus_1_to_file_off

